#!/usr/bin/env python3
"""Scripted OpenAI-compatible model for the real-backend Discovery browser suite.

This is a local deterministic fixture, not a supported/live model. It never
contacts an external provider. The `__mode` control endpoint lets a Playwright
test select a scenario (rejection, contradiction, provider failure, budget
exhaustion) without changing the backend.
"""
import json
import os
import sys
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATE = {
    "mode": "happy",
    "requests": 0,
    "evaluate_verdicts": 0,
    "fail_once": False,
}
LOCK = threading.Lock()


def fixture(name):
    with open(os.path.join(ROOT, "crates/tj-packet/fixtures", name), encoding="utf-8") as handle:
        return json.load(handle)


def plan_fixture():
    with open(os.path.join(ROOT, "crates/tj-plan/fixtures/complete.json"), encoding="utf-8") as handle:
        return json.load(handle)


def packet(mode):
    value = fixture("contradictory.json" if mode == "contradiction" else "complete.json")
    reference = (
        "artifact:collect:writer"
        if mode == "neutral_planning"
        else "artifact:discovery:evaluate"
    )
    for source in value.get("sources", []):
        source["kind"] = "stage_artifact"
        source["reference"] = reference
    return value


def text_response(text):
    return {
        "id": "chatcmpl-scripted",
        "object": "chat.completion",
        "model": "scripted-model",
        "choices": [{
            "index": 0,
            "message": {"role": "assistant", "content": text},
            "finish_reason": "stop",
        }],
        "usage": {"prompt_tokens": 17, "completion_tokens": 11, "total_tokens": 28},
    }


def tool_response(name, arguments):
    return {
        "id": "chatcmpl-scripted-tool",
        "object": "chat.completion",
        "model": "scripted-model",
        "choices": [{
            "index": 0,
            "message": {
                "role": "assistant",
                "content": None,
                "tool_calls": [{
                    "id": f"call_{name}_{STATE['requests']}",
                    "type": "function",
                    "function": {"name": name, "arguments": json.dumps(arguments)},
                }],
            },
            "finish_reason": "tool_calls",
        }],
        "usage": {"prompt_tokens": 23, "completion_tokens": 9, "total_tokens": 32},
    }


def write_then_verdict(stage, mode):
    """Publish the required interactive artifact, then complete via verdict."""
    response = verdict(stage, mode)
    call = response["choices"][0]["message"]["tool_calls"][0]
    marker = "success"
    if stage == "evaluate":
        marker = "proceed"
    write_call = {
        "id": f"call_write_{STATE['requests']}",
        "type": "function",
        "function": {
            "name": "write_file",
            "arguments": json.dumps({
                "path": "output.md",
                "content": f"# {stage} artifact\n\nverdict: {marker}\n\nGenerated by the local scripted TJ-026 fixture.",
            }),
        },
    }
    response["choices"][0]["message"]["tool_calls"] = [write_call, call]
    return response


def all_text(body):
    chunks = []
    for message in body.get("messages", []):
        content = message.get("content")
        if isinstance(content, str):
            chunks.append(content)
        elif isinstance(content, list):
            for part in content:
                if isinstance(part, dict) and isinstance(part.get("text"), str):
                    chunks.append(part["text"])
    return "\n".join(chunks).lower()


def answered(body):
    for message in body.get("messages", []):
        role = message.get("role")
        if role in ("tool", "function"):
            return True
        if message.get("tool_call_id"):
            return True
    return False


def stage_of(body):
    text = all_text(body)
    for marker, stage in (
        ("neutral surveyor", "survey"),
        ("neutral outliner", "outline"),
        ("neutral sketcher", "sketch"),
        ("neutral aligner", "align"),
        ("neutral planner", "plan"),
        ("neutral checker", "check"),
        ("neutral writer", "writer"),
    ):
        if marker in text:
            return stage
    if "convert a completed discovery" in text:
        return "packet"
    if "devil's advocate" in text or "skeptical engineering director" in text:
        return "evaluate"
    if "senior business analyst" in text:
        return "analyze"
    if "senior system architect" in text:
        return "architect"
    if "ux/ui design specialist" in text:
        return "design"
    if "technical program manager" in text:
        return "align"
    if "delivery planner" in text:
        return "plan"
    if "qa lead reviewing" in text:
        return "validate"
    return "intake"


def verdict(stage, mode):
    if stage == "evaluate":
        with LOCK:
            STATE["evaluate_verdicts"] += 1
            rejected = mode == "reject_once" and STATE["evaluate_verdicts"] == 1
        if rejected:
            return tool_response("verdict", {
                "verdict": "reject",
                "summary": "Requirements need a measurable cancellation outcome.",
                "content": "# Evaluation\n\nRejected once: the intake lacks a measurable outcome.",
                "unresolved": ["No measurable cancellation outcome was supplied."],
            })
        return tool_response("verdict", {
            "verdict": "proceed",
            "summary": "Requirements are specific enough to generate the packet.",
            "content": "# Evaluation\n\nProceed: the requested outcome and acceptance criteria are clear.",
            "rationale": "The user named the supported cancellation outcome and the evidence source.",
        })
    return tool_response("verdict", {
        "verdict": "success",
        "summary": "The user needs online cancellation with a clear refund preview.",
        "content": "# Requirements Extraction\n\nA solo traveller needs to cancel an eligible booking without contacting support and see the refund before confirming.",
    })


def question():
    return tool_response("question", {
        "question": "What outcome matters most to the traveller?",
        "options": [],
        "multi_select": False,
        "free_form": True,
    })


def build_response(body, mode):
    stage = stage_of(body)
    if stage in ("analyze", "architect", "design", "align", "survey", "outline", "sketch"):
        labels = {
            "analyze": "Structured requirements analysis",
            "architect": "Component and contract architecture",
            "design": "Interaction and accessibility design",
            "align": "Cross-stream alignment report",
            "survey": "Structured requirements survey",
            "outline": "Component and contract outline",
            "sketch": "Interaction and accessibility sketch",
        }
        return text_response(json.dumps({
            "verdict": "success",
            "summary": labels[stage],
            "content": f"# {labels[stage]}\n\nDerived only from the approved packet and the preceding planning artifact.",
        }))
    if stage == "plan":
        plan = plan_fixture()
        return text_response(json.dumps({
            "verdict": "success",
            "summary": "Traceable cancellation task plan validated against the approved packet.",
            "content": "# Structured task plan\n\nEvery task traces to the approved packet or states an enabling rationale.",
            "plan": plan,
        }))
    if stage in ("validate", "check"):
        return text_response(json.dumps({
            "verdict": "approved",
            "summary": "Plan coverage and dependencies are complete; no repository writes are implied.",
            "content": "# Plan validation\n\nDeterministic validation passed; every task traces to the approved packet or enabling rationale.",
        }))
    if stage == "writer" and mode == "neutral_planning":
        return text_response(json.dumps({
            "verdict": "generated",
            "summary": "Generated a reviewable requirements packet.",
            "content": "# Requirements packet\n\nGenerated from the approved intake artifact.",
            "packet": packet(mode),
        }))
    if stage == "packet":
        return text_response(json.dumps({
            "verdict": "generated",
            "summary": "Generated a reviewable requirements packet.",
            "content": "# Requirements packet\n\nGenerated from the intake and evaluation artifacts.",
            "packet": packet(mode),
        }))
    if mode == "endless_questions":
        return question()
    if not answered(body):
        return question()
    return write_then_verdict(stage, mode)


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass

    def send_json(self, status, value):
        payload = json.dumps(value).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        raw = self.rfile.read(length) if length else b"{}"
        if self.path == "/__mode":
            try:
                body = json.loads(raw or b"{}")
            except json.JSONDecodeError:
                self.send_json(400, {"error": "invalid mode body"})
                return
            with LOCK:
                STATE["mode"] = body.get("mode", "happy")
                STATE["requests"] = 0
                STATE["evaluate_verdicts"] = 0
                STATE["fail_once"] = False
            self.send_json(200, {"ok": True, "mode": STATE["mode"]})
            return
        if self.path == "/__state":
            self.send_json(200, dict(STATE))
            return
        try:
            body = json.loads(raw or b"{}")
        except json.JSONDecodeError:
            body = {}
        with LOCK:
            STATE["requests"] += 1
            mode = STATE["mode"]
            fail_once = mode == "provider_fail_once" and STATE["requests"] == 1
            credential = mode == "provider_credential"
        if credential:
            self.send_json(401, {"error": "invalid api key"})
            return
        if fail_once:
            self.send_json(503, {"error": "temporary upstream outage"})
            return
        response = build_response(body, mode)
        self.send_json(200, response)

    def do_GET(self):
        if self.path in ("/v1/models", "/__state"):
            if self.path == "/__state":
                self.send_json(200, dict(STATE))
            else:
                self.send_json(200, {"data": [{"id": "scripted-model", "object": "model"}]})
            return
        self.send_json(404, {"error": "not found"})


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 9188
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    server.serve_forever()


if __name__ == "__main__":
    main()
